// Rebuilds the data-driven parts of the site from the engine's own report.
//   node site/build.mjs            (run from the project folder)
// Reads ../reports/latest_recommendation.csv, writes site/data.js, and fills the marked blocks in site/index.html
// so the page is complete even before any script runs.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const csv = readFileSync(join(here, '..', 'reports', 'latest_recommendation.csv'), 'utf8').trim().split(/\r?\n/);
const head = csv[0].split(',');
const rows = csv.slice(1).map((line) => {
  const f = Object.fromEntries(line.split(',').map((v, i) => [head[i], v]));
  return {
    rank: Number(f.rank),
    universe: f.universe,
    strategy: f.strategy,
    verdict: f.verdict,
    score: Number(f.score),
    oosSharpe: Number(f.oos_sharpe),
    oosCagr: Number(f.oos_cagr),
    maxdd: Number(f.oos_maxdd),
    trades: Number(f.oos_trades),
    gap: Number(f.overfit_gap),
    baselineSharpe: Number(f.baseline_sharpe),
    baselineCagr: Number(f.baseline_cagr),
    windows: Number(f.n_windows),
    periodStart: f.period_start,
    periodEnd: f.period_end,
  };
});

await import(pathToFileURL(join(here, 'answer.js')).href);
const Q = globalThis.QuantAnswer;
const recommended = rows.filter((r) => r.verdict === 'RECOMMENDED').length;
const meta = { rows: rows.length, recommended, windows: rows[0].windows, periodStart: rows[0].periodStart, periodEnd: rows[0].periodEnd };
writeFileSync(join(here, 'data.js'), '// Generated by build.mjs from reports/latest_recommendation.csv. Do not edit.\nwindow.QUANT = ' + JSON.stringify({ meta, rows }, null, 1) + ';\n');

// ----- the table: grouped by strategy, groups ordered by their best rank -----
const order = [...new Set([...rows].sort((a, b) => a.rank - b.rank).map((r) => r.strategy))];
let table = '';
for (const s of order) {
  table += `<tbody>\n<tr class="grp"><th scope="colgroup" colspan="4">${Q.stratLabel(s)}</th></tr>\n`;
  for (const r of rows.filter((x) => x.strategy === s).sort((a, b) => a.rank - b.rank)) {
    table += `<tr data-reveal style="--i:0"><td>${Q.coinOf(r.universe)}</td><td class="nums">${Q.num(r.oosSharpe)}</td><td class="nums">${Q.num(r.baselineSharpe)}</td><td>${Q.VERDICT[r.verdict]}</td></tr>\n`;
  }
  table += '</tbody>\n';
}

// ----- the strip: every row on one axis of out-of-sample Sharpe -----
const MIN = -3.2, MAX = 1.4;
const x = (v) => (((v - MIN) / (MAX - MIN)) * 100).toFixed(2);
let lanes = '';
let n = 0;
for (const s of order) {
  let marks = '';
  for (const r of rows.filter((q) => q.strategy === s)) {
    const label = `${Q.coinOf(r.universe)}: ${Q.num(r.oosSharpe)} (buy-and-hold ${Q.num(r.baselineSharpe)})`;
    marks += `<span class="base" style="--x:${x(r.baselineSharpe)}%"></span>`;
    marks += `<span class="dot" style="--x:${x(r.oosSharpe)}%;--i:${n++}" tabindex="0" aria-label="${Q.esc(Q.stratLabel(s) + ' on ' + label)}"><b>${Q.esc(label)}</b></span>`;
  }
  lanes += `<div class="lane"><p class="lane-name">${Q.stratLabel(s)}</p><div class="track">${marks}</div></div>\n`;
}
const ticks = [-3, -2, -1, 0, 0.5, 1].map((t) => `<span style="--x:${x(t)}%">${t === 0.5 ? '0.5' : Q.num(t, 0)}</span>`).join('');
const strip = `<div class="plot"><div class="zone" style="--from:${x(0.5)}"></div>\n${lanes}<div class="axis"><p class="lane-name"></p><div class="track">${ticks}</div></div></div>`;

const defaultAnswer = Q.answer('Momentum on BTC', rows);

const file = join(here, 'index.html');
let html = readFileSync(file, 'utf8');
const fill = (name, body) => {
  const re = new RegExp(`(<!--${name}-->)[\\s\\S]*?(<!--/${name}-->)`);
  if (!re.test(html)) throw new Error('marker missing: ' + name);
  html = html.replace(re, (_, a, z) => `${a}\n${body}\n${z}`);
};
fill('TABLE', table);
fill('STRIP', strip);
fill('ANSWER', defaultAnswer);
writeFileSync(file, html);
console.log(`site built: ${rows.length} rows, ${recommended} recommended, strip + table + answer written`);
